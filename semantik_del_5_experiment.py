"""
SNLI + BERT + LSTM för Natural Language Inference (NLI)

Modellen fungerar enligt följande:

Premiss --------------------\
                             --> BERT --> LSTM --> Sammanfogning --> Klassificering
hypothesis --------------------/

Output:
0 = entailment
1 = contradiction
2 = neutral

Exempel:
Premiss: "A man is playing guitar."
hypothesis: "A person is making music."

=> entailment
"""

