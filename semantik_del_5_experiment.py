log= ""
with open("results.txt", "w") as f:
  f.write(log)

for epoch in range(EPOCHS):
    print(f"Beginning Epoch {epoch+1}/{EPOCHS}")
    log+=f"Beginning Epoch {epoch+1}/{EPOCHS}"
    with open("results.txt", "w") as f:
        f.write(log)
    model.train()

    total_loss = 0
    print("Batches: ", len(train_loader))
    counter = 1

    for batch in train_loader:

        if counter%10 == 0:
          pass
        print(f"Batch {counter}/{len(train_loader)}")
        counter += 1

        prem_ids = batch["prem_input_ids"].to(DEVICE)
        prem_att = batch["prem_attention"].to(DEVICE)

        hyp_ids = batch["hyp_input_ids"].to(DEVICE)
        hyp_att = batch["hyp_attention"].to(DEVICE)

        labels = batch["label"].to(DEVICE)

        optimizer.zero_grad()

        logits = model(
            prem_ids,
            prem_att,
            hyp_ids,
            hyp_att
        )

        loss = criterion(
            logits,
            labels
        )

        loss.backward()

        optimizer.step()

        total_loss += loss.item()
        print("Loss in batch: ", total_loss )
    avg_loss = total_loss / len(train_loader)

    print(f"Ending Epoch {epoch+1}/{EPOCHS} "f"Loss: {avg_loss:.4f}")
    log+=f"Ending Epoch {epoch+1}/{EPOCHS} "f"Loss: {avg_loss:.4f}"
    with open("results.txt", "w") as f:
        f.write(log)

# EVALUERING


model.eval()

correct = 0
total = 0

with torch.no_grad():

    for batch in valid_loader:

        prem_ids = batch["prem_input_ids"].to(DEVICE)
        prem_att = batch["prem_attention"].to(DEVICE)

        hyp_ids = batch["hyp_input_ids"].to(DEVICE)
        hyp_att = batch["hyp_attention"].to(DEVICE)

        labels = batch["label"].to(DEVICE)

        logits = model(
            prem_ids,
            prem_att,
            hyp_ids,
            hyp_att
        )

        predictions = torch.argmax(
            logits,
            dim=1
        )

        correct += (
            predictions == labels
        ).sum().item()

        total += labels.size(0)

accuracy = correct / total

print(f"\nVal Accuracy: {accuracy:.4f}")
log+=f"\nVal Accuracy: {accuracy:.4f}"
