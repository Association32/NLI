# TOKENIZER


tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)

# bert-class


class SNLIDataset(Dataset):
    """
    Turn SNLI into  tensors.
    """

    def __init__(self, dataset):
        self.dataset = dataset

    def __len__(self):
        return len(self.dataset)

    def __getitem__(self, idx):

        row = self.dataset[idx]

        premise = row["premise"]
        hypothesis = row["hypothesis"]

        label = row["label"]

        # Tokenize premis
        prem_enc = tokenizer(
            premise,
            truncation=True,
            padding="max_length",
            max_length=MAX_LENGTH,
            return_tensors="pt"
        )

        ## Tokenize hypothesis
        hyp_enc = tokenizer(
            hypothesis,
            truncation=True,
            padding="max_length",
            max_length=MAX_LENGTH,
            return_tensors="pt"
        )

        return {
            "prem_input_ids":
                prem_enc["input_ids"].squeeze(0),

            "prem_attention":
                prem_enc["attention_mask"].squeeze(0),

            "hyp_input_ids":
                hyp_enc["input_ids"].squeeze(0),

            "hyp_attention":
                hyp_enc["attention_mask"].squeeze(0),

            "label":
                torch.tensor(label)
        }

# DATALOADER


train_loader = DataLoader(
    SNLIDataset(train_data),
    batch_size=BATCH_SIZE,
    shuffle=True
)

valid_loader = DataLoader(
    SNLIDataset(valid_data),
    batch_size=BATCH_SIZE
)

# model


class BertLSTMNLI(nn.Module):


    def __init__(self):

        super().__init__()

        # Förtränad BERT
        self.bert = AutoModel.from_pretrained(MODEL_NAME)

        bert_dim = self.bert.config.hidden_size
        # bert-base = 768

        # LSTM som arbetar på BERT-utdata
        self.lstm = nn.LSTM(
            input_size=bert_dim,
            hidden_size=256,
            num_layers=1,
            batch_first=True,
            bidirectional=True
        )



        # 256 * 2 = 512 as  LSTM is bidirectional
        sentence_dim = 512

        # Premiss + hypothesis
        combined_dim = sentence_dim * 2

        self.classifier = nn.Sequential(

            nn.Linear(combined_dim, 256),

            nn.ReLU(),

            nn.Dropout(0.2),

            nn.Linear(256, 3)
        )

    def encode_sentence(
        self,
        input_ids,
        attention_mask
    ):



        # BERT


        bert_output = self.bert(
            input_ids=input_ids,
            attention_mask=attention_mask
        )

        """
        last_hidden_state:

        Shape:
        [batch, seq_len, 768]
        """

        sequence_output = bert_output.last_hidden_state


        # LSTM


        _, (hidden, _) = self.lstm(
            sequence_output
        )

        """
        hidden shape:

        [2, batch, 256]

        eftersom bidirectional=True

        hidden[0] = framåt
        hidden[1] = bakåt
        """

        forward_hidden = hidden[0]

        backward_hidden = hidden[1]

        # combining directions
        sentence_vector = torch.cat(
            [forward_hidden, backward_hidden],
            dim=1
        )

        return sentence_vector

    def forward(
        self,
        prem_input_ids,
        prem_attention,
        hyp_input_ids,
        hyp_attention
    ):

        #premiss
        prem_vector = self.encode_sentence(
            prem_input_ids,
            prem_attention
        )

        # hypothesis
        hyp_vector = self.encode_sentence(
            hyp_input_ids,
            hyp_attention
        )

        # Sammanfoga båda meningarna
        combined = torch.cat(
            [prem_vector, hyp_vector],
            dim=1
        )

        logits = self.classifier(combined)

        return logits

